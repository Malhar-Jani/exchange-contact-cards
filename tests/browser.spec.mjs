import {test, expect} from '@playwright/test';
import {PNG} from 'pngjs';
import jsQR from 'jsqr';
import {makeVCard, emptyCard} from '../src/vcard.mjs';

test('generate, decode, download and manage event presets on desktop and mobile', async ({page}) => {
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5174/');
  await expect(page.getByRole('button',{name:'QR image',exact:true})).toBeDisabled();
  const card={...emptyCard,firstName:'Malhar',lastName:'Jani',phone:'+919876543210',email:'test@example.com',organization:'Business Club',title:'Member',website:'https://example.com',note:'We met at an event. Hello, again; keep in touch!'};
  await page.getByPlaceholder('e.g. eSummit 2027').fill('Test Event');
  for(const [label,value] of [['First name',card.firstName],['Last name',card.lastName],['Phone number',card.phone],['Email address',card.email],['Company or organisation',card.organization],['Role',card.title],['Website or social link',card.website],['Contact note',card.note]]) await page.getByLabel(label,{exact:false}).fill(value);
  await expect(page.locator('.qr-area img')).toBeVisible();
  const src=await page.locator('.qr-area img').getAttribute('src');
  const png=PNG.sync.read(Buffer.from(src.split(',')[1],'base64'));
  const decoded=jsQR(new Uint8ClampedArray(png.data),png.width,png.height);
  expect(decoded?.data).toBe(makeVCard(card)); expect(decoded?.data).not.toContain('Test Event');
  const previewPng=PNG.sync.read(await page.locator('.qr-area img').screenshot());
  expect(jsQR(new Uint8ClampedArray(previewPng.data),previewPng.width,previewPng.height)?.data).toBe(makeVCard(card));
  await page.getByRole('button',{name:'Save event preset',exact:true}).click();
  await page.reload(); await expect(page.getByLabel('First name')).toHaveValue('Malhar');
  await expect(page.getByRole('combobox')).toContainText('Test Event');
  const filePromise=page.waitForEvent('download'); await page.getByRole('button',{name:'Contact file',exact:true}).click();
  const file=await filePromise; expect(file.suggestedFilename()).toBe('Malhar Jani.vcf');
  const imagePromise=page.waitForEvent('download'); await page.getByRole('button',{name:'QR image',exact:true}).click();
  expect((await imagePromise).suggestedFilename()).toBe('Malhar Jani-qr.png');
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Show QR full screen'}).click(); await expect(page.getByRole('dialog')).toBeVisible(); await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'Use these details for another event'}).click(); await expect(page.getByLabel('First name')).toHaveValue('Malhar');
  await page.getByPlaceholder('e.g. eSummit 2027').fill('Second event'); await page.getByRole('button',{name:'Save event preset',exact:true}).click();
  await page.getByRole('combobox').selectOption({label:'Test Event'}); await expect(page.getByPlaceholder('e.g. eSummit 2027')).toHaveValue('Test Event');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Show my QR',exact:true}).click(); await expect(page.getByRole('dialog')).toBeVisible();
  const phonePng=PNG.sync.read(await page.locator('.presentation img').screenshot());
  expect(jsQR(new Uint8ClampedArray(phonePng.data),phonePng.width,phonePng.height)?.data).toBe(makeVCard(card));
  await page.screenshot({path:'test-results/mobile-qr.png',fullPage:true});
  await page.getByRole('button',{name:'Close full screen QR'}).click();
  page.once('dialog', d=>d.accept()); await page.getByRole('button',{name:'Delete event preset'}).click();
  await expect(page.getByRole('combobox')).not.toContainText('Test Event'); expect(errors).toEqual([]);
});
